const ChildSuggestionCard: React.FC<{
  field: FormField;
  schema: FormSchema;
  suggestion: RelatedSuggestion;
  onAdd: () => void;
}> = ({ field, schema, suggestion, onAdd }) => {
  const childSource = getSourceById(suggestion.sourceId);
  if (!childSource) return null;
  const alreadyExists = (schema.sections || []).some((s) =>
    (s.fields || []).some(
      (f) =>
        f.apiSelectEndpoint === childSource.endpoint &&
        (f.apiSelectEndpointParams || []).includes(field.key),
    ),
  );
  if (alreadyExists) return null;

  return (
    <div className="rounded-md border border-amber-200 bg-amber-50 p-2 flex items-start gap-2">
      <span className="text-base leading-none">💡</span>
      <div className="flex-1 space-y-1">
        <p className="text-[11px] text-amber-900 leading-snug">{suggestion.promptText}</p>
        <button
          type="button"
          onClick={onAdd}
          className="inline-flex items-center gap-1 px-2 py-1 text-xs font-medium text-amber-900 bg-amber-100 hover:bg-amber-200 border border-amber-300 rounded"
        >
          <Plus className="h-3.5 w-3.5" />
          Adicionar campo de {suggestion.defaultLabel}
        </button>
      </div>
    </div>
  );
};

/* ────────────────────────────────────────────────────────────────────────── */

const ParentSuggestionGroup: React.FC<{
  field: FormField;
  schema: FormSchema;
  selectedSource: DatabaseSource;
  onLinkExisting: (parentKey: string) => void;
  onCreateParent: (parentSource: DatabaseSource, parentLabel: string) => void;
}> = ({ field, schema, selectedSource, onLinkExisting, onCreateParent }) => {
  return (
    <>
      {(selectedSource.parents || []).map((sug) => {
        const parentSource = getSourceById(sug.sourceId);
        if (!parentSource) return null;
        const allExisting = collectExistingByEndpoint(schema, field.key, parentSource.endpoint);
        // Só mostra como candidato pra vincular os campos cujo key é aceito pelo
        // backend nessa cascata. Senão, o vínculo não funcionaria em runtime.
        const accepted = parentSource.acceptedParentKeys;
        const existingParents = accepted
          ? allExisting.filter((p) => accepted.includes(p.key))
          : allExisting;
        return (
          <ParentSuggestionCard
            key={sug.sourceId}
            suggestion={sug}
            parentSource={parentSource}
            existingParents={existingParents}
            onLinkExisting={onLinkExisting}
            onCreateParent={onCreateParent}
          />
        );
      })}
    </>
  );
};

function collectExistingByEndpoint(
  schema: FormSchema,
  currentKey: string,
  endpoint: string,
): Array<{ key: string; label: string }> {
  const out: Array<{ key: string; label: string }> = [];
  for (const s of schema.sections || []) {
    for (const f of s.fields || []) {
      if (!f.key || f.key === currentKey) continue;
      if (f.dataSource === 'api' && f.apiSelectEndpoint === endpoint) {
        out.push({ key: f.key, label: (f.label || '').trim() || f.key });
      }
    }
  }
  return out;
}

const ParentSuggestionCard: React.FC<{
  suggestion: RelatedSuggestion;
  parentSource: DatabaseSource;
  existingParents: Array<{ key: string; label: string }>;
  onLinkExisting: (parentKey: string) => void;
  onCreateParent: (parentSource: DatabaseSource, parentLabel: string) => void;
}> = ({ suggestion, parentSource, existingParents, onLinkExisting, onCreateParent }) => {
  return (
    <div className="rounded-md border border-amber-200 bg-amber-50 p-2 space-y-2">
      <p className="text-[11px] text-amber-900 leading-snug">
        <span className="text-base leading-none mr-1">💡</span>
        {suggestion.promptText}
      </p>
      <div className="flex flex-wrap gap-2">
        {existingParents.map((p) => (
          <button
            key={p.key}
            type="button"
            onClick={() => onLinkExisting(p.key)}
            className="inline-flex items-center gap-1 px-2 py-1 text-xs font-medium text-amber-900 bg-amber-100 hover:bg-amber-200 border border-amber-300 rounded"
          >
            <Link2 className="h-3.5 w-3.5" />
            Vincular à pergunta «{p.label}»
          </button>
        ))}
        <button
          type="button"
          onClick={() => onCreateParent(parentSource, suggestion.defaultLabel)}
          className="inline-flex items-center gap-1 px-2 py-1 text-xs font-medium text-amber-900 bg-amber-100 hover:bg-amber-200 border border-amber-300 rounded"
        >
          <Plus className="h-3.5 w-3.5" />
          {existingParents.length > 0
            ? `Criar outro campo de ${suggestion.defaultLabel} acima`
            : `Criar campo de ${suggestion.defaultLabel} acima`}
        </button>
      </div>
    </div>
  );
};

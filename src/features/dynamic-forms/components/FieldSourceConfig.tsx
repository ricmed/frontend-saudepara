interface ParentInfo {
  hasParent: boolean;
  parentKey?: string;
  parentLabel?: string;
  parentMissing?: boolean;
  candidates: Array<{ key: string; label: string; sourceId?: string }>;
}

function getParentInfo(field: FormField, schema: FormSchema): ParentInfo {
  const params = field.apiSelectEndpointParams || [];
  const parentKey = params[0];
  const candidates: Array<{ key: string; label: string; sourceId?: string }> = [];
  let parentLabel: string | undefined;
  for (const s of schema.sections || []) {
    for (const f of s.fields || []) {
      if (!f.key || f.key === field.key) continue;
      if (f.type === 'select' || f.type === 'select-search') {
        const src = inferDatabaseSource(f);
        candidates.push({
          key: f.key,
          label: (f.label || '').trim() || f.key,
          sourceId: src?.id,
        });
        if (f.key === parentKey) parentLabel = (f.label || '').trim() || f.key;
      }
    }
  }
  return {
    hasParent: !!parentKey,
    parentKey,
    parentLabel,
    parentMissing: !!parentKey && !parentLabel,
    candidates,
  };
}

const ParentLinkBadge: React.FC<{
  parentInfo: ParentInfo;
  onChangeParent: (newKey: string) => void;
  onUnlink: () => void;
}> = ({ parentInfo, onChangeParent, onUnlink }) => {
  const [editing, setEditing] = React.useState(false);

  if (parentInfo.parentMissing) {
    return (
      <div className="rounded-md border border-amber-200 bg-amber-50 p-2 flex items-center justify-between gap-2">
        <div className="flex items-start gap-2 flex-1">
          <Link2 className="h-4 w-4 text-amber-700 mt-0.5 flex-shrink-0" />
          <p className="text-[11px] text-amber-900 leading-snug flex-1">
            Vínculo desatualizado — a pergunta de origem não existe mais.
            {parentInfo.candidates.length > 0 && ' Escolha outra ou remova o vínculo.'}
          </p>
        </div>
        <div className="flex gap-2 flex-shrink-0">
          {parentInfo.candidates.length > 0 && (
            <button
              type="button"
              className="text-[11px] text-amber-900 underline hover:text-amber-700"
              onClick={() => setEditing(true)}
            >
              Vincular a outra
            </button>
          )}
          <button
            type="button"
            className="text-[11px] text-amber-900/80 underline hover:text-amber-700"
            onClick={onUnlink}
          >
            Remover vínculo
          </button>
        </div>
      </div>
    );
  }

  if (editing) {
    return (
      <div className="rounded-md border border-blue-200 bg-blue-50 p-2 space-y-1">
        <p className="text-[11px] font-medium text-blue-900">Vincular a qual pergunta?</p>
        <div className="flex gap-2">
          <select
            className="flex-1 px-2 py-1.5 text-xs border border-blue-200 rounded bg-white"
            value={parentInfo.parentKey ?? ''}
            onChange={(e) => {
              onChangeParent(e.target.value);
              setEditing(false);
            }}
          >
            <option value="">— Selecione —</option>
            {parentInfo.candidates.map((o) => (
              <option key={o.key} value={o.key}>
                {o.label}
              </option>
            ))}
          </select>
          <button
            type="button"
            className="px-2 py-1.5 text-xs text-gray-600 hover:bg-gray-100 rounded"
            onClick={() => setEditing(false)}
          >
            Cancelar
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="rounded-md border border-green-200 bg-green-50 p-2 flex items-center justify-between gap-2">
      <div className="flex items-start gap-2">
        <Link2 className="h-4 w-4 text-green-700 mt-0.5 flex-shrink-0" />
        <div className="text-[11px] text-green-900 leading-snug">
          <strong className="font-semibold">Vinculado à pergunta «{parentInfo.parentLabel}»</strong>
          <span className="block text-green-800/80">A lista filtra pelo valor dessa pergunta.</span>
        </div>
      </div>
      <div className="flex gap-2 flex-shrink-0">
        <button
          type="button"
          className="text-[11px] text-green-900 underline hover:text-green-700"
          onClick={() => setEditing(true)}
        >
          Trocar
        </button>
        <button
          type="button"
          className="text-[11px] text-green-900/80 underline hover:text-green-700"
          onClick={onUnlink}
        >
          Remover vínculo
        </button>
      </div>
    </div>
  );
};


import React from 'react';
import { Check, Link2, Plus } from 'lucide-react';
import type { FormField, FormSchema } from '@/services/FormService';
import {
  DATABASE_SOURCES,
  applyDatabaseSource,
  getSourceById,
  inferDatabaseSource,
  type DatabaseSource,
  type RelatedSuggestion,
} from '../utils/databaseSources';
import { DF_CHOICE_WITH_TEXT_DEFAULT_VALUE } from '@/features/dynamic-forms/utils/radioChoiceOther';

/**
 * Configuração de "de onde vêm as opções" de um campo de seleção.
 *
 * Duas escolhas primárias: `Lista manual` (digitada) e `Base de dados` (do sistema).
 * Em `Base de dados`, o dropdown lista TODAS as bases conhecidas (1 entrada por base).
 * As cascatas aparecem como ações:
 *   - Se a base tem filhos sugeridos: banner "Adicionar campo filho abaixo".
 *   - Se a base tem pais sugeridos e o campo ainda não está vinculado:
 *     banner "Vincular a campo existente ou criar campo de pai acima".
 *
 * Schema permanece igual (`dataSource`, `apiSelectEndpoint`, `apiSelectEndpointParams`,
 * ...).
 */

export type AddRelatedFieldRequest =
  | {
      kind: 'addChildBelow';
      parentField: FormField;
      childSource: DatabaseSource;
      childLabel: string;
    }
  | {
      kind: 'addParentAbove';
      childField: FormField;
      parentSource: DatabaseSource;
      parentLabel: string;
    };

interface FieldSourceConfigProps {
  field: FormField;
  schema: FormSchema;
  onChange: (updates: Partial<FormField>) => void;
  onAddRelatedField: (req: AddRelatedFieldRequest) => void;
}

type PrimaryMode = 'manual' | 'database';

function inferPrimary(field: FormField): PrimaryMode {
  if (!field.dataSource || field.dataSource === 'manual') return 'manual';
  return 'database';
}

export const FieldSourceConfig: React.FC<FieldSourceConfigProps> = ({
  field,
  schema,
  onChange,
  onAddRelatedField,
}) => {
  const primary = inferPrimary(field);
  const selectedSource = inferDatabaseSource(field);
  const parentInfo = getParentInfo(field, schema);

  const setManual = () => {
    onChange({
      dataSource: 'manual',
      dataTable: undefined,
      dataValueColumn: undefined,
      dataLabelColumn: undefined,
      apiSelectEndpoint: undefined,
      apiSelectEndpointParams: undefined,
      apiSelectStaticParams: undefined,
      apiListGuidedPreset: undefined,
    });
  };

  const setDatabaseEmpty = () => {
    onChange({
      dataSource: 'api',
      options: undefined,
      dataTable: undefined,
      dataValueColumn: undefined,
      dataLabelColumn: undefined,
      apiSelectEndpoint: undefined,
      apiSelectEndpointParams: undefined,
      apiSelectStaticParams: undefined,
      apiListGuidedPreset: undefined,
    });
  };

  const applySource = (source: DatabaseSource) => {
    const update: Partial<FormField> = applyDatabaseSource(source);

    // Se a base costuma ser usada como pai de cascata, o backend só reconhece
    // certos nomes de query param. Renomeia o key do campo pra um aceito,
    // a menos que o usuário já tenha customizado o key manualmente.
    if (source.acceptedParentKeys && source.acceptedParentKeys.length > 0) {
      const currentKey = field.key || '';
      const alreadyOk = source.acceptedParentKeys.includes(currentKey);
      const looksAutoGenerated = /^field_/.test(currentKey);
      if (!alreadyOk && looksAutoGenerated) {
        const preferred = source.acceptedParentKeys[0];
        const used = new Set<string>();
        for (const s of schema.sections || []) {
          for (const f of s.fields || []) {
            if (f.key && f.key !== currentKey) used.add(f.key);
          }
        }
        let newKey = preferred;
        if (used.has(newKey)) {
          let n = 2;
          while (used.has(`${preferred}_${n}`)) n++;
          newKey = `${preferred}_${n}`;
        }
        update.key = newKey;
      }
    }

    onChange(update);
  };

  return (
    <div className="mt-3 p-3 border border-gray-200 rounded-lg bg-gray-50 space-y-3">
      <PrimaryPicker
        field={field}
        current={primary}
        onSelectManual={setManual}
        onSelectDatabase={setDatabaseEmpty}
      />

      {primary === 'manual' && <ManualOptions field={field} onChange={onChange} />}

      {(field.type === 'radio' || field.type === 'select' || field.type === 'checkbox-group') && (
        <ChoiceWithTextConfig field={field} onChange={onChange} />
      )}

      {primary === 'database' && (
        <div className="space-y-3 p-3 bg-white border border-gray-200 rounded-lg">
          {/* Badge de vínculo (filho de outro campo) */}
          {parentInfo.hasParent && (
            <ParentLinkBadge
              parentInfo={parentInfo}
              onChangeParent={(newKey) =>
                onChange({ apiSelectEndpointParams: newKey ? [newKey] : undefined })
              }
              onUnlink={() => onChange({ apiSelectEndpointParams: undefined })}
            />
          )}

          <BaseDropdown selectedSource={selectedSource} onSelect={applySource} />

          {/* Sugestão de FILHO */}
          {selectedSource?.children?.map((sug) => (
            <ChildSuggestionCard
              key={sug.sourceId}
              field={field}
              schema={schema}
              suggestion={sug}
              onAdd={() => {
                const childSource = getSourceById(sug.sourceId);
                if (!childSource) return;
                onAddRelatedField({
                  kind: 'addChildBelow',
                  parentField: field,
                  childSource,
                  childLabel: sug.defaultLabel,
                });
              }}
            />
          ))}

          {/* Sugestão de PAI */}
          {selectedSource?.parents && !parentInfo.hasParent && (
            <ParentSuggestionGroup
              field={field}
              schema={schema}
              selectedSource={selectedSource}
              onLinkExisting={(parentKey) => onChange({ apiSelectEndpointParams: [parentKey] })}
              onCreateParent={(parentSource, parentLabel) =>
                onAddRelatedField({
                  kind: 'addParentAbove',
                  childField: field,
                  parentSource,
                  parentLabel,
                })
              }
            />
          )}
        </div>
      )}
    </div>
  );
};


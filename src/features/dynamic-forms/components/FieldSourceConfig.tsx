const PrimaryPicker: React.FC<{
  field: FormField;
  current: PrimaryMode;
  onSelectManual: () => void;
  onSelectDatabase: () => void;
}> = ({ field, current, onSelectManual, onSelectDatabase }) => {
  const groupName = `dataSource_${field.key || field.id || Math.random().toString(36).slice(2)}`;
  const cards: Array<{ value: PrimaryMode; title: string; hint: string; onClick: () => void }> = [
    { value: 'manual', title: 'Lista manual', hint: 'Você digita cada opção', onClick: onSelectManual },
    { value: 'database', title: 'Base de dados', hint: 'Lista pronta do sistema', onClick: onSelectDatabase },
  ];
  return (
    <div>
      <label className="block text-xs font-medium text-gray-700 mb-2">O que esta pergunta lista?</label>
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
        {cards.map(({ value, title, hint, onClick }) => {
          const isSelected = current === value;
          return (
            <label
              key={value}
              className={`flex items-start gap-3 p-4 rounded-xl cursor-pointer transition-all duration-200 ${
                isSelected
                  ? 'bg-blue-50 border-2 border-blue-500 shadow-md scale-[1.02]'
                  : 'bg-white border-2 border-gray-200 hover:border-blue-300 hover:bg-blue-50/50 hover:shadow-sm'
              }`}
            >
              <div className="flex items-center h-5 mt-0.5 flex-shrink-0">
                <input
                  type="radio"
                  name={groupName}
                  checked={isSelected}
                  onChange={onClick}
                  className="w-5 h-5 rounded-full border-2 border-gray-300 text-blue-600 focus:ring-2 focus:ring-blue-500 cursor-pointer"
                />
              </div>
              <div className="flex-1 min-w-0 flex flex-col justify-center gap-0.5">
                <span className={`text-sm font-medium ${isSelected ? 'text-blue-900' : 'text-gray-900'}`}>
                  {title}
                </span>
                <span className="text-[11px] text-gray-500 leading-snug">{hint}</span>
              </div>
              {isSelected && (
                <div className="flex items-center flex-shrink-0">
                  <Check className="h-5 w-5 text-blue-600" />
                </div>
              )}
            </label>
          );
        })}
      </div>
    </div>
  );
};


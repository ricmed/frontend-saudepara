export function normalizeMunicipioNameForBandeira(name: string): string {
  return name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9-]/g, '');
}

/**
 * Slug no nome do ficheiro em `public/images/bandeiras_pa_mini/`
 * (por vezes não coincide com `normalizeMunicipioNameForBandeira`, ex.: Pau D'Arco → `pau-d-arco`).
 */
function getBandeiraMiniFileSlug(canonicalMunicipioName: string): string {
  if (canonicalMunicipioName === "Pau D'Arco") {
    return 'pau-d-arco';
  }
  return normalizeMunicipioNameForBandeira(canonicalMunicipioName);
}

/**
 * Cadastro/API às vezes difere do nome oficial usado nas bandeiras (e nas chaves do mapa).
 * Valor = nome oficial presente em `municipioBandeiraCodigosPa` e no slug do arquivo em public.
 */
const MUNICIPIO_BANDEIRA_NOME_OFICIAL: Record<string, string> = {
  'Santa Izabel do Pará': 'Santa Isabel do Pará',
  'Eldorado do Carajás': 'Eldorado dos Carajás',
  'Eldorado do Carajas': 'Eldorado dos Carajás',
  'Pau D Arco': "Pau D'Arco",
  "Pau d'Arco": "Pau D'Arco",
  'Pau DArco': "Pau D'Arco",
  'Pau Darco': "Pau D'Arco",
  "Pau D' Arco": "Pau D'Arco",
  "Pau d' Arco": "Pau D'Arco",
};

function sanitizeMunicipioNomeApi(raw: string): string {
  let s = raw
    .trim()
    .replace(/\u00A0/g, ' ')
    // apóstrofos / acentos usados no lugar de ' em cadastros
    .replace(/[\u2018\u2019\u201A\u201B\u00B4\u02BC\u02B9]/g, "'")
    .replace(/\s+/g, ' ');
  // Ex.: "Pau D' Arco" (espaço após o apóstrofo) → "Pau D'Arco"
  s = s.replace(/\b(Pau\s+D)'\s+(Arco)\b/gi, "$1'$2");
  return s;
}

function resolveNomeOficialBandeira(raw: string): string {
  const cleaned = sanitizeMunicipioNomeApi(raw);
  const direct = MUNICIPIO_BANDEIRA_NOME_OFICIAL[cleaned];
  if (direct) return direct;
  const lower = cleaned.toLowerCase();
  const hit = Object.entries(MUNICIPIO_BANDEIRA_NOME_OFICIAL).find(([k]) => k.toLowerCase() === lower);
  return hit ? hit[1] : cleaned;
}

/** Caminho SEM extensão (.jpg / .png conforme existir no public). */
export function getMunicipioBandeiraPathBase(municipioName: string): string {
  const official = resolveNomeOficialBandeira(municipioName);
  let codigo = municipioBandeiraCodigosPa[official];
  let slugFrom = official;

  if (!codigo) {
    const targetNorm = normalizeMunicipioNameForBandeira(official);
    // Nome do cadastro que normaliza para slug diferente do ficheiro, mas é Pau D'Arco.
    if (targetNorm === 'pau-d-arco' || targetNorm === 'pau-darco') {
      slugFrom = "Pau D'Arco";
      codigo = municipioBandeiraCodigosPa[slugFrom];
    } else {
      const matches = Object.entries(municipioBandeiraCodigosPa).filter(
        ([k]) => normalizeMunicipioNameForBandeira(k) === targetNorm
      );
      if (matches.length === 1) {
        slugFrom = matches[0][0];
        codigo = matches[0][1];
      }
    }
  }

  const fileSlug = getBandeiraMiniFileSlug(slugFrom);
  if (codigo) {
    return `/images/bandeiras_pa_mini/municipio-${fileSlug}-bandeira-mini-${codigo}`;
  }
  return `/images/bandeiras_pa_mini/municipio-${fileSlug}-bandeira-mini`;
}